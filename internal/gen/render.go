package gen

import (
	"bytes"
	"embed"
	"fmt"
	"go/format"
	"io/fs"
	"path"
	"strings"
	"text/template"

	"github.com/donaldgifford/mcp-go-gen/internal/ir"
)

// templatesFS embeds the whole templates tree at build time. Filenames are
// preserved verbatim — the renderer uses them as both the template key and
// (after stripping the .tmpl suffix) as a hint for the output extension.
//
//go:embed templates
var templatesFS embed.FS

// generatedHeader is stamped at the top of every generated Go file so that
// reviewers and the mcpgen:hook DST logic can recognize managed files.
const generatedHeader = "// Code generated by mcp-go-gen. DO NOT EDIT.\n"

// Render executes every Plan derived from spec and commits the results via
// w. On any render or format failure, no file reaches disk — the renderer
// collects all buffers in memory first and only calls w.Commit() once every
// Plan has rendered cleanly.
//
// The Plans slice is computed by BuildPlans(spec). Tests that want to
// exercise rendering in isolation can call BuildPlans + render themselves.
func Render(spec *ir.Spec, w Writer) error {
	plans, err := BuildPlans(spec)
	if err != nil {
		return fmt.Errorf("build plans: %w", err)
	}

	tmpls, err := loadTemplates()
	if err != nil {
		return fmt.Errorf("load templates: %w", err)
	}

	buffers := make(map[string][]byte, len(plans))
	for _, p := range plans {
		rendered, renderErr := renderPlan(tmpls, p)
		if renderErr != nil {
			return fmt.Errorf("render %s: %w", p.Path, renderErr)
		}
		buffers[p.Path] = rendered
	}

	for path, content := range buffers {
		if err := w.Write(path, content); err != nil {
			return fmt.Errorf("buffer %s: %w", path, err)
		}
	}
	return w.Commit()
}

// loadTemplates parses every *.tmpl file below templates/ into a single
// Template with the associated filename (relative to templates/) as its
// name. The resulting Template can be looked up via ExecuteTemplate.
func loadTemplates() (*template.Template, error) {
	root := template.New("").Funcs(funcMap())
	walkErr := fs.WalkDir(templatesFS, "templates", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(p, ".tmpl") {
			return nil
		}
		body, readErr := fs.ReadFile(templatesFS, p)
		if readErr != nil {
			return readErr
		}
		name := strings.TrimPrefix(p, "templates/")
		if _, parseErr := root.New(name).Parse(string(body)); parseErr != nil {
			return fmt.Errorf("parse %s: %w", name, parseErr)
		}
		return nil
	})
	if walkErr != nil {
		return nil, walkErr
	}
	return root, nil
}

func renderPlan(tmpls *template.Template, p Plan) ([]byte, error) {
	t := tmpls.Lookup(p.Template)
	if t == nil {
		return nil, fmt.Errorf("template %q not found", p.Template)
	}

	var buf bytes.Buffer
	if p.GoFormat {
		buf.WriteString(generatedHeader)
	}
	if err := t.Execute(&buf, p.Data); err != nil {
		return nil, fmt.Errorf("execute: %w", err)
	}

	if !p.GoFormat {
		return buf.Bytes(), nil
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("go/format: %w\n---\n%s", err, buf.String())
	}
	return formatted, nil
}

// funcMap returns the helper functions exposed to every template. Kept tiny
// on purpose — heavy logic belongs in BuildPlans or the IR converter, not
// in template expression syntax.
func funcMap() template.FuncMap {
	return template.FuncMap{
		"goIdent":  goIdent,
		"snake":    snakeCase,
		"joinPath": path.Join,
		"quotedOr": quotedOr,
	}
}

// goIdent converts a snake_case or kebab-case string into a Go exported
// identifier (PascalCase). Used by tool-handler templates to turn tool
// names like "get_rfc" into handler method names like "GetRfc".
func goIdent(s string) string {
	if s == "" {
		return ""
	}
	var b strings.Builder
	upper := true
	for _, r := range s {
		if r == '_' || r == '-' || r == ' ' {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(toUpper(r))
			upper = false
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

func toUpper(r rune) rune {
	if r >= 'a' && r <= 'z' {
		return r - ('a' - 'A')
	}
	return r
}

// snakeCase returns s lowercased with dashes replaced by underscores. Used
// by templates that need to render stable metric label values.
func snakeCase(s string) string {
	return strings.ToLower(strings.ReplaceAll(s, "-", "_"))
}

// quotedOr returns the Go source literal for s, or the literal for
// fallback if s is empty. Keeps template conditionals shorter.
func quotedOr(s, fallback string) string {
	if s == "" {
		return fmt.Sprintf("%q", fallback)
	}
	return fmt.Sprintf("%q", s)
}
